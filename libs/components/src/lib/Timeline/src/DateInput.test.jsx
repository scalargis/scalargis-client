import React from 'react';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import DateInput from './DateInput';
vi.mock('@mantine/core', () => ({ TextInput: React.forwardRef((props, ref) => <input {...props} ref={ref} />) }));
afterEach(cleanup);
it('preserves incomplete native segments until blur and keeps external navigation in sync', () => {
  const commit = vi.fn(value => value || null);
  const props = { type: 'datetime-local', 'aria-label': 'date', value: '2026-11-19T23:20', onCommit: commit, onEdit: vi.fn() };
  const view = render(<DateInput {...props} />);
  const field = screen.getByLabelText('date');
  fireEvent.focus(field);
  fireEvent.input(field, { target: { value: '' } });
  view.rerender(<DateInput {...props} value="2026-11-19T23:30" />);
  expect(field.value).toBe('');
  fireEvent.input(field, { target: { value: '2024-09-17T23:10' } });
  expect(commit).not.toHaveBeenCalled();
  fireEvent.blur(field);
  expect(commit).toHaveBeenCalledWith('2024-09-17T23:10');
  view.rerender(<DateInput {...props} value="2024-09-18T23:10" />);
  expect(field.value).toBe('2024-09-18T23:10');
});
it('commits with Enter and restores invalid or cancelled edits', () => {
  const commit = vi.fn(value => value || null);
  render(<DateInput type="date" aria-label="date" value="2026-11-19" onCommit={commit} onEdit={vi.fn()} />);
  const field = screen.getByLabelText('date');
  field.focus();
  fireEvent.input(field, { target: { value: '2024-09-17' } });
  fireEvent.keyDown(field, { key: 'Enter' });
  expect(commit).toHaveBeenLastCalledWith('2024-09-17');
  field.focus();
  fireEvent.input(field, { target: { value: '' } });
  fireEvent.blur(field);
  expect(field.value).toBe('2026-11-19');
  field.focus();
  fireEvent.input(field, { target: { value: '2023-01-01' } });
  fireEvent.keyDown(field, { key: 'Escape' });
  expect(field.value).toBe('2026-11-19');
});
